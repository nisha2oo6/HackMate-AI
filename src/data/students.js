// Safely read saved student profile changes from Local Storage.
function getSavedProfiles() {
  try {
    return JSON.parse(
      localStorage.getItem("hackmateStudentProfiles") || "{}"
    );
  } catch (error) {
    console.error("Unable to read saved student profiles:", error);
    return {};
  }
}

// Read all students, including their saved profile changes.
export function getAllStudents() {
  const savedProfiles = getSavedProfiles();

  return students.map((student) => ({
    ...student,
    ...(savedProfiles[student.id] || {}),
  }));
}

// Get one student's latest profile.
export function getStudentById(studentId) {
  return getAllStudents().find(
    (student) => student.id === Number(studentId)
  );
}

// Save profile changes without modifying the original sample data.
export function saveStudentProfile(studentId, updatedProfile) {
  const savedProfiles = getSavedProfiles();

  savedProfiles[studentId] = {
    ...(savedProfiles[studentId] || {}),
    ...updatedProfile,
  };

  localStorage.setItem(
    "hackmateStudentProfiles",
    JSON.stringify(savedProfiles)
  );
}
